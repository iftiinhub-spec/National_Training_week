import { chromium } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(process.cwd(), '..');
const out = path.join(process.cwd(), 'test-results', 'profile-mobile-nav');
fs.mkdirSync(out, { recursive: true });
const env = fs.readFileSync(path.join(root, 'backend', '.env'), 'utf8');
const value = (key) => env.match(new RegExp(`^${key}=(.*)$`, 'm'))?.[1]?.trim().replace(/^['"]|['"]$/g, '');
const browser = await chromium.launch({ headless: true, executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe' });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const failures = [];
page.on('pageerror', (error) => failures.push(error.message));
const signIn = async (email, password, target) => { await page.goto('http://localhost:5173/signin'); await page.getByPlaceholder('name@domain.com').fill(email); await page.locator('input[type="password"]').fill(password); await page.getByRole('button', { name: /Sign In to Portal/i }).click(); await page.waitForURL(new RegExp(target)); };
await signIn(value('ADMIN_EMAIL'), value('ADMIN_PASSWORD'), '/admin');
await page.getByRole('link', { name: 'My Profile', exact: true }).click();
await page.getByText('Administrator profile', { exact: true }).waitFor();
await page.getByRole('button', { name: /Edit profile/i }).waitFor();
await page.screenshot({ path: path.join(out, 'admin-profile-desktop.png'), fullPage: true });
await page.getByRole('button', { name: /Sign Out/i }).click();
await page.setViewportSize({ width: 390, height: 844 });
await signIn('ibrahimkhaliil5280@gmail.com', 'Participant123!', '/portal');
const mobileNav = page.getByRole('navigation', { name: /Participant mobile navigation/i });
await mobileNav.waitFor();
const links = await mobileNav.getByRole('link').count();
if (links !== 5) throw new Error(`Expected 5 mobile tabs, found ${links}`);
const navBox = await mobileNav.boundingBox();
if (!navBox || navBox.width < 380) throw new Error(`Mobile navigation is not full width (${navBox?.width || 0}px)`);
const tabBoxes = await mobileNav.getByRole('link').evaluateAll((elements) => elements.map((element) => element.getBoundingClientRect()).map(({ x, y, width }) => ({ x, y, width })));
if (new Set(tabBoxes.map((box) => Math.round(box.y))).size !== 1) throw new Error('Mobile tabs are stacking vertically');
if (await page.getByRole('button', { name: /Open participant menu/i }).count()) throw new Error('Legacy participant menu toggle is still visible');
await page.getByRole('button', { name: /Open participant account menu/i }).click();
await page.getByRole('menuitem', { name: /My Profile/i }).waitFor();
await page.getByRole('menuitem', { name: /Sign Out/i }).waitFor();
const overflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth + 2);
if (overflow) throw new Error('Participant mobile portal has horizontal overflow');
await page.screenshot({ path: path.join(out, 'participant-mobile-bottom-tabs.png'), fullPage: true });
await browser.close();
console.log(JSON.stringify({ passed: true, adminProfile: true, participantMobileTabs: links, horizontalOverflow: overflow, browserErrors: failures }, null, 2));
